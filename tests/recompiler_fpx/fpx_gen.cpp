// Writes the C the differential driver links: every word of words.h translated
// by the current emitter into ops_soft.c (the default, ABI 5 text) and
// ops_fpx.c (FPX1), each with its runtime header; the two negative controls
// ops_nokeep.c and ops_nomid.c; and hw.c, which runs the same words on an
// AArch64 host.
#include <cstdio>
#include <filesystem>
#include <fstream>
#include <string>
#include "core/recompiler/arm64_to_c.h"

extern "C" {
#include "words.h"
}

namespace {

bool Write(const std::filesystem::path& path, const std::string& text) {
    std::filesystem::create_directories(path.parent_path());
    std::ofstream out(path, std::ios::binary);
    out.write(text.data(), static_cast<std::streamsize>(text.size()));
    return static_cast<bool>(out);
}

// The runtime C includes "recomp_runtime.h"; point it at the header written here.
std::string Renamed(std::string text, const std::string& header) {
    const std::string from = "#include \"recomp_runtime.h\"";
    for (size_t at = text.find(from); at != std::string::npos; at = text.find(from, at))
        text.replace(at, from.size(), "#include \"" + header + "\"");
    return text;
}

// Replaces the one occurrence of `from` in `text`; false if it is missing.
bool Replace(std::string& text, const std::string& from, const std::string& to) {
    const size_t at = text.find(from);
    if (at == std::string::npos || text.find(from, at + 1) != std::string::npos) {
        std::fprintf(stderr, "control edit not found: %s\n", from.c_str());
        return false;
    }
    text.replace(at, from.size(), to);
    return true;
}

// Replaces every occurrence of `from` in `text`.
void ReplaceAll(std::string& text, const std::string& from, const std::string& to) {
    for (size_t at = text.find(from); at != std::string::npos; at = text.find(from, at + to.size()))
        text.replace(at, from.size(), to);
}

// One translation unit of op functions plus its table, named g_ops_<tag>.
// `rename` renames the shared exact bodies the ops call (the broken control
// carries its own copies under another name).
bool Ops(const std::filesystem::path& dir, const std::string& tag, const std::string& header,
         bool rename = false) {
    std::string out = "/* Generated by fpx_gen. */\n#include \"" + header +
                      "\"\n#include <string.h>\n#include <math.h>\n";
    std::string table = "typedef void (*FpxOpFn)(GuestContext*);\nconst FpxOpFn g_ops_" + tag + "[]={";
    for (unsigned i = 0; i < FPX_NWORDS; ++i) {
        std::string code;
        bool unhandled = false;
        suyu::recomp::Translate(g_fpx_words[i].word, 0x100, code, &unhandled);
        if (unhandled) {
            std::fprintf(stderr, "unhandled %08x %s\n", g_fpx_words[i].word, g_fpx_words[i].text);
            return false;
        }
        if (rename) ReplaceAll(code, "recomp_fpe_", "recomp_fpeb_");
        out += "static void op" + std::to_string(i) + "(GuestContext*c){\n" + code + "}\n";
        table += "op" + std::to_string(i) + ",";
    }
    return Write(dir / ("ops_" + tag + ".c"), out + table + "};\n");
}

// Native execution: q0-q3, x0, x1 and NZCV from `in`, FPCR from the argument,
// FPSR cleared; q0, x0 and NZCV to `out`, FPSR returned.
std::string Hw() {
    std::string out = "/* Generated by fpx_gen. AArch64 hosts only. */\n#include <stdint.h>\n";
    std::string table = "typedef uint64_t (*FpxHwFn)(const uint64_t*,uint64_t*,uint64_t);\n"
                        "const FpxHwFn g_hw[]={";
    for (unsigned i = 0; i < FPX_NWORDS; ++i) {
        char word[16];
        std::snprintf(word, sizeof word, "0x%08x", g_fpx_words[i].word);
        out += "static uint64_t hw" + std::to_string(i) +
               "(const uint64_t* in,uint64_t* out,uint64_t fpcr){ uint64_t fs;\n"
               " __asm__ volatile(\"ldr q0,[%1]\\n ldr q1,[%1,#16]\\n ldr q2,[%1,#32]\\n"
               " ldr q3,[%1,#48]\\n ldr x0,[%1,#64]\\n ldr x1,[%1,#72]\\n ldr x9,[%1,#80]\\n"
               " msr nzcv,x9\\n msr fpcr,%3\\n msr fpsr,xzr\\n .inst " +
               std::string(word) +
               "\\n mrs %0,fpsr\\n msr fpcr,xzr\\n str q0,[%2]\\n str x0,[%2,#16]\\n"
               " mrs x9,nzcv\\n str x9,[%2,#24]\\n\""
               " : \"=&r\"(fs) : \"r\"(in),\"r\"(out),\"r\"(fpcr)"
               " : \"v0\",\"v1\",\"v2\",\"v3\",\"x0\",\"x1\",\"x9\",\"cc\",\"memory\"); return fs; }\n";
        table += "hw" + std::to_string(i) + ",";
    }
    return out + table + "};\n";
}

} // namespace

int main(int argc, char** argv) {
    if (argc != 2) {
        return 2;
    }
    const std::filesystem::path dir = argv[1];
    suyu::recomp::g_translate_all = true;
    // The runtime C only for recomp_fp_estimate, which a few estimate forms call.
    if (!Write(dir / "rt_soft.h", suyu::recomp::RuntimeH()) ||
        !Write(dir / "rt_soft.c", Renamed(suyu::recomp::RuntimeC(), "rt_soft.h")) ||
        !Ops(dir, "soft", "rt_soft.h") ||
        !Write(dir / "hw.c", Hw())) {
        return 1;
    }
    // FPX1, and the two negative controls: the same text with the keep test
    // reduced to "always" (the D-style build), and without the midpoint test.
    suyu::recomp::g_emit_fpx = true;
    const std::string fpx = suyu::recomp::RuntimeH();
    std::string nokeep = fpx, nomid = fpx;
    const bool edited =
        Replace(nokeep, "#define RECOMP_FPX_BIG32(t) ", "#define RECOMP_FPX_BIG32(t) (1) || ") &&
        Replace(nokeep, "#define RECOMP_FPX_FIN32(t) ", "#define RECOMP_FPX_FIN32(t) (1) || ") &&
        Replace(nokeep, "#define RECOMP_FPX_BIG64(t) ", "#define RECOMP_FPX_BIG64(t) (1) || ") &&
        Replace(nokeep, "#define RECOMP_FPX_FIN64(t) ", "#define RECOMP_FPX_FIN64(t) (1) || ") &&
        Replace(nomid, "#define RECOMP_FPX_MIDPOINT(s) ", "#define RECOMP_FPX_MIDPOINT(s) (0) && ");
    // Only the fpx ops count their fast-path hits.
    const std::string probe = "extern unsigned long long g_fpx_probe[3];\n"
                              "#define RECOMP_FPX_PROBE(k) (++g_fpx_probe[k])\n";
    if (!edited || !Write(dir / "rt_fpx.h", probe + fpx) || !Write(dir / "rt_nokeep.h", nokeep) ||
        !Write(dir / "rt_nomid.h", nomid) || !Ops(dir, "fpx", "rt_fpx.h") ||
        !Ops(dir, "nokeep", "rt_nokeep.h") || !Ops(dir, "nomid", "rt_nomid.h")) {
        return 1;
    }
    // FPX1 with the shared exact bodies (FPE): the same words, their exact
    // bodies out of line in fpxs_rt.c. Must match the inline form bit for bit.
    suyu::recomp::g_emit_fp_shared = true;
    const std::string fpxs = suyu::recomp::RuntimeH();
    const std::string fpe_c = suyu::recomp::FpeRuntimeC();
    // Negative control: its own copies (renamed so they link beside the real ones) with
    // the inexact flag dropped from the first body that raises it.
    std::string broken_h = fpxs, broken_c = fpe_c;
    ReplaceAll(broken_h, "recomp_fpe_", "recomp_fpeb_");
    ReplaceAll(broken_c, "recomp_fpe_", "recomp_fpeb_");
    const std::string inexact = "c->fpsr|=16;";
    const size_t inexact_at = broken_c.find(inexact);
    if (inexact_at == std::string::npos) {
        std::fprintf(stderr, "control edit not found: %s\n", inexact.c_str());
        return 1;
    }
    broken_c.erase(inexact_at, inexact.size());
    const auto rt_file = [](const std::string& header, const std::string& body) {
        return "#include \"" + header + "\"\n#include <string.h>\n" + body;
    };
    if (!Write(dir / "rt_fpxs.h", probe + fpxs) || !Write(dir / "fpxs_rt.c", rt_file("rt_fpxs.h", fpe_c)) ||
        !Ops(dir, "fpxs", "rt_fpxs.h") || !Write(dir / "rt_fpxb.h", probe + broken_h) ||
        !Write(dir / "fpxb_rt.c", rt_file("rt_fpxb.h", broken_c)) ||
        !Ops(dir, "fpxb", "rt_fpxb.h", true)) {
        return 1;
    }
    // FPXV: the all-lane vector FADD/FSUB on top of the shared build (it reuses fpxs_rt.c's
    // bodies). ops_fpxvb.c is the negative control: its helper keeps a lane whose result is
    // not finite, so it must differ from the exact body wherever a lane overflows or is NaN.
    suyu::recomp::g_emit_fpx_vec = true;
    const std::string fpxv = suyu::recomp::RuntimeH();
    std::string fpxvb = fpxv, fpxvz = fpxv;
    if (!Replace(fpxvb, "declined = _mm_cmpeq_epi32(_mm_and_si128(t, exp_mask), exp_mask);",
                 "declined = zero;") ||
        !Write(dir / "rt_fpxv.h", probe + fpxv) || !Ops(dir, "fpxv", "rt_fpxv.h") ||
        // And one that forgets that FZ flushes subnormal inputs.
        !Replace(fpxvz, "declined = _mm_or_si128(_mm_or_si128(sub_a, sub_b), ", "declined = _mm_or_si128(zero, ") ||
        !Write(dir / "rt_fpxvb.h", probe + fpxvb) || !Ops(dir, "fpxvb", "rt_fpxvb.h") ||
        !Write(dir / "rt_fpxvz.h", probe + fpxvz) || !Ops(dir, "fpxvz", "rt_fpxvz.h")) {
        return 1;
    }
    suyu::recomp::g_emit_fpx_vec = false;
    suyu::recomp::g_emit_fp_shared = false;
    // The shadow instrumentation build: exact results always, with the fast
    // path compared behind them (recomp_fpx_shadow, from the runtime C).
    suyu::recomp::g_emit_fpx_shadow = true;
    if (!Write(dir / "rt_shadow.h", suyu::recomp::RuntimeH()) ||
        !Write(dir / "shadow_rt.c",
               "#include \"rt_shadow.h\"\n#include <stdlib.h>\n" +
                   std::string(suyu::recomp::FpxShadowC())) ||
        !Ops(dir, "shadow", "rt_shadow.h")) {
        return 1;
    }
    return 0;
}
